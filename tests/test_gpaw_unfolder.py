def test_lcao_gamma_group_sums_are_integers(lcao):
    """Pristine Gamma: exact-integer degenerate group weights summing to 8."""
    prim, sc, unf = lcao
    res = unf.compute(np.zeros((1, 3)), method="ring")
    total = res.weights[0].sum()
    assert abs(total - 8.0) < 1e-6
    sums = _group_sums(res.eigenvalues[0], res.weights[0])
    assert np.abs(sums - np.round(sums)).max() < 1e-6
    # each group carries an integer multiple of the single-fold weight
    assert sums.min() > -1e-8 and sums.max() < 4 + 1e-8


def test_lcao_generic_k_binary(lcao):
    """Pristine generic-k ideal weights are 0/1 to the table accuracy.

    Nyquist-shell splitting keeps the interpolated overlap Hermitian;
    finite orbital/shell coverage still limits generic-k precision.
    The plane-wave route below seals much sharper binary weights.
    """
    prim, sc, unf = lcao
    kg = np.array([[0.137, 0.062, 0.0]])
    res = unf.compute(kg, method="ideal")
    w = res.weights[0]
    assert np.abs(w * (1.0 - w)).max() < 0.05
    assert abs(w.sum() - 8.0) < 1e-3


def test_lcao_gamma_bands_match_primitive(lcao):
    """SC Gamma spectrum = primitive bands at the four star k-points.

    The star of the conventional-cell Gamma contains Gamma and the three
    X points of the primitive lattice; their primitive bands must appear
    in the supercell Gamma spectrum up to the potential-reference
    difference between the two independent GPAW runs.
    """
    from scipy.linalg import eigh

    prim, sc, unf = lcao
    h_sc, s_sc = sc.hs_and_eigen([0.0, 0.0, 0.0])
    e_sc = np.sort(eigh(h_sc, s_sc, eigvals_only=True))
    star = [(0, 0, 0), (0, 0.5, 0.5), (0.5, 0, 0.5), (0.5, 0.5, 0)]
    ref = np.sort(np.concatenate([
        np.sort(eigh(*prim.hs_and_eigen(k), eigvals_only=True)) for k in star
    ]))
    assert e_sc.shape == ref.shape
    assert np.abs(e_sc - ref).max() < 0.1


def test_si7p_gamma_parseval_and_defect_weight(si7p):
    """Si:P Gamma: near-Parseval total, bounded groups, fractional groups.

    On the defect supercell the single-k weight sum need not be exactly
    the primitive orbital count (translation symmetry is broken), so the
    total carries a small deficit; the dopant signature is the set of
    genuinely fractional degenerate-group weights.
    """
    prim, sc, unf = si7p
    res = unf.compute(np.zeros((1, 3)), method="ring")
    w = res.weights[0]
    assert abs(w.sum() - 8.0) < 0.1
    sums = _group_sums(res.eigenvalues[0], res.weights[0])
    assert sums.min() > -1e-3 and sums.max() < 4 + 1e-3
    fractional = sums[(sums > 1e-2) & (sums < 1.0 - 1e-2)]
    assert fractional.size >= 3, "too few fractional groups: dopant signature lost"


def test_pw_generic_k_binary(pw):
    """Planewave unfolding of the pristine path is strictly binary.

    The four highest stored bands are excluded: top-of-bank states of
    the path SCF converge loosely and their coefficients are not
    trustworthy to binary-weight accuracy; every resolved band (16
    occupied + 4 conduction) is binary to 1e-4.
    """
    data, unf, kprim = pw
    res = unf.compute(kprim[::7], resolve_degenerate=1e-3)
    w = res.weights[:, :20]
    assert np.abs(w * (1.0 - w)).max() < 1e-4
    # every requested point found its stored SC momentum
    assert res.sc_kpoints.shape == kprim[::7].shape

def test_pw_si7p_gamma_fold_partition_and_fractional_donor():
    """A real Si:P PW Gamma eigenstate partitions over four folds."""
    pytest.importorskip("gpaw")
    from HamiltonIO.gpaw import GpawPWParser
    from unfolding.pw_unfolder import PWEigenData, PWUnfolder

    data = GpawPWParser(_require_fixture("si7p_pw.gpw")).read()
    eigen = PWEigenData(data.kpoints, data.gvecs,
                        [c[None, :, None, :] for c in data.coefficients],
                        data.eigenvalues[:, None, :])
    folds = [[0, 0, 0], [0, .5, .5], [.5, 0, .5], [.5, .5, 0]]
    result = PWUnfolder(eigen, B).compute(folds)
    np.testing.assert_allclose(result.weights.sum(axis=0), 1, atol=1e-12)
    donor = result.weights[:, 16]
    assert donor.min() > 0.05 and donor.max() < 0.4
