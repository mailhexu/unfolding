"""GPAW-backend end-to-end validation on real fixtures (story 017).

Fixtures: ``tests/data/gpaw_example/*.gpw`` generated by
``examples/gpaw_si/generate_fixtures.py`` (gpaw >= 26 new calculators,
serial, PBE, Gamma-centered grids; see that script for run parameters).

Sealed here:

1. LCAO route: the pristine 8-atom conventional cell, unfolded onto the
   primitive fcc path with supercell matrix B. At Gamma the degenerate
   group weight sums are exact integers totalling 8 (= primitive orbital
   count), and at a generic k the ideal weights are binary 0/1.
2. The supercell Gamma spectrum is the primitive Gamma spectrum four
   times (host bands match the GPAW primitive-cell band structure).
3. Si:P (match_species=False, P carries 4 AOs/atom like Si): Parseval
   total weight 8 at Gamma, every group weight in [0, 2], and at least
   one genuinely fractional group (the dopant signature).
4. Planewave route: the pristine conventional-cell path run unfolds to
   strictly binary weights at generic k.
"""
import os

import numpy as np
import pytest

DATA = os.path.join(os.path.dirname(__file__), "data", "gpaw_example")
B = np.array([[-1, 1, 1], [1, -1, 1], [1, 1, -1]])  # conv cell = B @ prim cell

# fcc special points in primitive reciprocal fractional coordinates
SPECIAL = {
    "G": (0.0, 0.0, 0.0), "X": (0.5, 0.0, 0.5),
    "W": (0.5, 0.25, 0.75), "L": (0.5, 0.5, 0.5),
}
PATH = "GXWGLWX"


def _group_sums(evals, weights, tol=1e-6):
    """Weight sums over consecutive (energy-sorted) degenerate runs."""
    order = np.argsort(evals)
    e, w = evals[order], weights[order]
    out, start = [], 0
    for i in range(1, len(e) + 1):
        if i == len(e) or e[i] - e[i - 1] > tol:
            out.append(float(w[start:i].sum()))
            start = i
    return np.array(out)


def _require_fixture(name):
    path = os.path.join(DATA, name)
    if not os.path.exists(path):
        pytest.skip(f"fixture missing: {name} (run examples/gpaw_si/"
                    "generate_fixtures.py)")
    return path


